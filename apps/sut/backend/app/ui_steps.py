"""UI step vocabulary: validation, normalisation and script export.

A step is a small dict:

    {"action": "goto",  "value": "http://127.0.0.1:8000/ui/"}
    {"action": "fill",  "target": "input[name=q]", "value": "工单"}
    {"action": "click", "target": "text=查询"}
    {"action": "assert_text", "target": "body", "value": "共 3 条"}

`target` accepts a CSS selector or Playwright's ``text=`` / ``role=`` syntax.
"""

from __future__ import annotations

import json
from typing import Any

ACTIONS = {
    "goto",
    "click",
    "fill",
    "press",
    "select",
    "hover",
    "wait",
    "assert_text",
    "assert_visible",
    "assert_url",
    "screenshot",
}
NEEDS_TARGET = {"click", "fill", "press", "select", "hover", "assert_text", "assert_visible"}
NEEDS_VALUE = {"goto", "fill", "press", "select", "assert_text", "assert_url"}


class StepError(ValueError):
    """A step the runner cannot execute as written."""


def normalise_step(raw: Any, index: int) -> dict[str, Any]:
    if not isinstance(raw, dict):
        raise StepError(f"第 {index + 1} 步不是对象")
    action = str(raw.get("action") or "").strip().lower()
    if action not in ACTIONS:
        raise StepError(f"第 {index + 1} 步的 action「{action}」不支持")
    step: dict[str, Any] = {"action": action}
    name = str(raw.get("name") or "").strip()
    step["name"] = name or f"{action} {raw.get('target') or raw.get('value') or ''}".strip()
    if action in NEEDS_TARGET:
        target = str(raw.get("target") or "").strip()
        if not target:
            raise StepError(f"第 {index + 1} 步缺少 target")
        step["target"] = target
    if action in NEEDS_VALUE:
        value = raw.get("value")
        if value is None or (isinstance(value, str) and not value.strip()):
            raise StepError(f"第 {index + 1} 步缺少 value")
        step["value"] = str(value)
    if action == "wait":
        try:
            step["ms"] = max(0, min(30000, int(raw.get("ms") or raw.get("value") or 800)))
        except (TypeError, ValueError) as exc:
            raise StepError(f"第 {index + 1} 步的等待时长不是数字") from exc
    timeout = raw.get("timeout")
    if timeout is not None:
        try:
            step["timeout"] = max(500, min(60000, int(timeout)))
        except (TypeError, ValueError) as exc:
            raise StepError(f"第 {index + 1} 步的 timeout 不是数字") from exc
    return step


def normalise_steps(raw: Any) -> list[dict[str, Any]]:
    if isinstance(raw, str):
        text = raw.strip()
        if not text:
            return []
        try:
            raw = json.loads(text)
        except json.JSONDecodeError as exc:
            raise StepError("步骤不是合法 JSON") from exc
    if raw is None:
        return []
    if not isinstance(raw, list):
        raise StepError("步骤必须是数组")
    if not raw:
        return []
    if len(raw) > 40:
        raise StepError("单条用例最多 40 步")
    return [normalise_step(item, index) for index, item in enumerate(raw)]


def parse_env(raw: Any) -> dict[str, str]:
    if isinstance(raw, str):
        text = raw.strip()
        if not text:
            return {}
        try:
            raw = json.loads(text)
        except json.JSONDecodeError as exc:
            raise StepError("环境变量不是合法 JSON") from exc
    if raw in (None, ""):
        return {}
    if not isinstance(raw, dict):
        raise StepError("环境变量要是对象")
    return {str(key): str(value) for key, value in raw.items()}


def _py_literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_script(title: str, base_url: str, env: dict[str, str], steps: list[dict[str, Any]]) -> str:
    """Produce a standalone Playwright script that a human can run directly."""
    lines = [
        '"""Generated by ai-qa-lab · UI automation.',
        "",
        f"用例：{title}",
        f"Base URL：{base_url or '(未设置)'}",
        '"""',
        "",
        "from playwright.sync_api import sync_playwright",
        "",
        "",
        "def run() -> None:",
        "    with sync_playwright() as playwright:",
        "        browser = playwright.chromium.launch(headless=True)",
        "        context = browser.new_context()",
    ]
    if env:
        payload = _py_literal(env)
        lines += [
            "        # 免登录：先把登录态写进 localStorage，再打开页面",
            f"        injection = {payload}",
            "        script = (",
            '            "(() => { const data = %s; "',
            '            "for (const [k, v] of Object.entries(data)) localStorage.setItem(k, v); })();"',
            '            % __import__("json").dumps(injection)',
            "        )",
            "        context.add_init_script(script)",
        ]
    lines += [
        "        page = context.new_page()",
        "        page.set_default_timeout(10000)",
    ]
    for step in steps:
        action = step["action"]
        if action == "goto":
            url = step["value"]
            lines.append(f"        page.goto({_py_literal(url)})")
        elif action == "click":
            lines.append(f"        page.locator({_py_literal(step['target'])}).click()")
        elif action == "fill":
            lines.append(
                f"        page.locator({_py_literal(step['target'])}).fill({_py_literal(step['value'])})"
            )
        elif action == "press":
            lines.append(
                f"        page.locator({_py_literal(step['target'])}).press({_py_literal(step['value'])})"
            )
        elif action == "select":
            lines.append(
                f"        page.locator({_py_literal(step['target'])}).select_option({_py_literal(step['value'])})"
            )
        elif action == "hover":
            lines.append(f"        page.locator({_py_literal(step['target'])}).hover()")
        elif action == "wait":
            lines.append(f"        page.wait_for_timeout({int(step['ms'])})")
        elif action == "assert_text":
            lines.append(
                f"        assert {_py_literal(step['value'])} in page.locator("
                f"{_py_literal(step['target'])}).inner_text()"
            )
        elif action == "assert_visible":
            lines.append(f"        assert page.locator({_py_literal(step['target'])}).is_visible()")
        elif action == "assert_url":
            lines.append(f"        assert {_py_literal(step['value'])} in page.url")
        elif action == "screenshot":
            lines.append('        page.screenshot(path="step.png", full_page=True)')
    lines += ["        browser.close()", "", "", 'if __name__ == "__main__":', "    run()", ""]
    return "\n".join(lines)
